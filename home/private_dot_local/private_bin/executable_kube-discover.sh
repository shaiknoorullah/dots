#!/usr/bin/env bash
# kube-discover.sh — find this machine's kubeconfigs and publish KUBECONFIG locally.
#
# WHY: this repo is public, so it names no cluster, no context and no kubeconfig file. The tunnel
# conf, its unit and the SSH keys are copied by hand (docs/install.md §2), exactly like ~/.secrets
# and the reverse-tunnel env. dots ships the mechanism; the machine supplies the names.
#
# Reads (all local, none in the repo):
#   ~/.config/dots/kube.default        optional override: one KUBECONFIG value, wins outright
#   ~/.kube/config, then ~/.kube/*.yaml|*.yml|*.conf in C order
# Writes (both regenerated on every apply, neither managed by chezmoi):
#   ~/.config/dots/kube.env            sourced by zsh, waybar-kube.sh and hyprland.lua
#   ~/.config/environment.d/50-kube.conf   read by the systemd user manager at session start
# Nothing found -> both files are removed and KUBECONFIG stays unset; every consumer degrades quietly.
set -uo pipefail

cfg="${XDG_CONFIG_HOME:-$HOME/.config}"
env_file="$cfg/dots/kube.env"
sysd_file="$cfg/environment.d/50-kube.conf"

value=""
if [ -r "$cfg/dots/kube.default" ]; then
  # first non-comment, non-blank line; a bare path or a KUBECONFIG=... line both work
  value=$(sed -e 's/[[:space:]]*#.*$//' -e 's/^[[:space:]]*KUBECONFIG=//' "$cfg/dots/kube.default" \
          | grep -v '^[[:space:]]*$' | head -n 1 | tr -d '[:space:]')
fi

if [ -z "$value" ]; then
  files=()
  # ~/.kube/config first: kubectl writes context switches to the first entry, so the file kubectl
  # already owns stays the one that changes. It has no extension, so the find below cannot repeat it.
  [ -r "$HOME/.kube/config" ] && files+=("$HOME/.kube/config")
  while IFS= read -r f; do
    [ -n "$f" ] && files+=("$f")
  done < <(find "$HOME/.kube" -maxdepth 1 -type f \
             \( -name '*.yaml' -o -name '*.yml' -o -name '*.conf' \) 2>/dev/null | LC_ALL=C sort)
  [ ${#files[@]} -eq 0 ] || value=$(IFS=:; printf '%s' "${files[*]}")
fi

if [ -z "$value" ]; then
  rm -f "$env_file" "$sysd_file"
  systemctl --user unset-environment KUBECONFIG 2>/dev/null || true
  echo "kube-discover: no kubeconfig under ~/.kube; KUBECONFIG left unset"
  exit 0
fi

write() {  # path, contents — atomic, 0600 (the names are this machine's business, not the repo's)
  local p=$1 c=$2
  mkdir -p "${p%/*}"
  printf '%s\n' "$c" > "$p.tmp" && chmod 600 "$p.tmp" && mv "$p.tmp" "$p"
}
write "$env_file"  "# generated by kube-discover.sh — edits are overwritten on the next apply
export KUBECONFIG=$value"
write "$sysd_file" "# generated by kube-discover.sh — edits are overwritten on the next apply
KUBECONFIG=$value"

# make it true for the session that is already running, not just the next login
systemctl --user set-environment "KUBECONFIG=$value" 2>/dev/null || true
echo "kube-discover: KUBECONFIG=$value"
